# =============================================================================
# 課堂即時練習 2-2-2  雙向選擇 (if-else)
# 【題目】面試資格初審系統
# 【任務描述】
# 請撰寫程式讓用戶輸入「工作年資」。
# 若年資滿 2 年（含）以上，顯示「符合面試資格」；
# 否則顯示「資歷尚未達標，您的履歷已存入人才庫備查」。
# =============================================================================

work_years = int(input("請輸入工作年資: "))

if work_years >= 2:
    print("符合面試資格")
else:
    print("資歷尚未達標，您的履歷已存入人才庫備查")
# =============================================================================
# 方式一: 匯入整個模組
# =============================================================================
import exlotto

# 呼叫 exlotto 模組中的 lotto 函式
list1 = exlotto.lotto(48, 6)

# 將中獎號碼由小到大排序
print(sorted(list1))
print("=================================")



# =============================================================================
# 方式二: 只拿需要的工具 from...import
# =============================================================================
from exlotto import lotto

list1 = lotto(48, 6)
print(sorted(list1))
print("=================================")



# =============================================================================
# 方式: 為模組取一個綽號 import....as....
# =============================================================================
import exlotto as loto

list1 = loto.lotto(48, 6)
print(sorted(list1))